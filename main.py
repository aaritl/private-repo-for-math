def calculate_entropy_weights(normalized_df):

    weights = {}

    valid_columns = [
        col for col in normalized_df.columns
        if normalized_df[col].notna().sum() > 1
        and normalized_df[col].nunique(dropna=True) > 1
    ]

    if not valid_columns:
        return pd.Series(dtype=float)

    df = normalized_df[valid_columns].copy()

    n = len(df)

    if n <= 1:
        return pd.Series(dtype=float)

    epsilon = 1e-12

    for col in df.columns:

        values = df[col].copy()

        # Calculate proportions using available observations only.
        values = values.clip(lower=0)

        total = values.sum()

        if total <= 0:
            weights[col] = 0
            continue

        p = values / total

        p = p.replace(0, epsilon)

        entropy = -np.sum(p * np.log(p)) / np.log(n)

        divergence = max(0, 1 - entropy)

        weights[col] = divergence

    weights = pd.Series(weights, dtype=float)

    if weights.sum() == 0:
        return pd.Series(
            1 / len(weights),
            index=weights.index
        )

    return weights / weights.sum()


