def column_overlap_score(series, target_names, normalizer):

    values = series.dropna().astype(str).head(5000)

    if len(values) == 0:
        return 0, 0

    normalized = set(
        values.apply(normalizer).dropna()
    )

    normalized.discard("")

    if not normalized:
        return 0, 0

    overlap = normalized.intersection(target_names)

    return len(overlap), len(normalized)


def detect_geo_columns(df):

    region_candidates = []
    country_candidates = []

    for col in df.columns:

        # Skip geometry objects
        if col == "geometry":
            continue

        region_overlap, region_total = column_overlap_score(
            df[col],
            BOUNDARY_REGION_NAMES,
            normalize_place
        )

        country_overlap, country_total = column_overlap_score(
            df[col],
            BOUNDARY_COUNTRY_NAMES,
            normalize_country
        )

        # Region columns should overlap actual ADM1 names.
        if region_overlap > 0:
            region_candidates.append(
                (region_overlap, region_total, col)
            )

        # Country columns should overlap country names.
        if country_overlap > 0:
            country_candidates.append(
                (country_overlap, country_total, col)
            )

    region_col = (
        sorted(region_candidates, reverse=True)[0][2]
        if region_candidates else None
    )

    country_col = (
        sorted(country_candidates, reverse=True)[0][2]
        if country_candidates else None
    )

    # Do not use one column for both roles.
    if region_col == country_col:
        region_col = None

    return region_col, country_col, region_candidates, country_candidates


