# 2. DETECT AND REPAIR CSV HEADERS
# ------------------------------------------------------------

def repair_csv_header(df, max_rows=30):

    df = df.copy()

    # If headers already exist, retain them.
    if not all(
        str(c).lower().startswith("unnamed")
        for c in df.columns
    ):
        return df

    best_row = None
    best_score = -1

    keywords = [
        "country", "location", "city", "region",
        "year", "urban", "water", "sanitation",
        "population", "indicator", "service",
        "percentage", "geoarea"
    ]

    # Search the first 30 rows for the actual header.
    for i in range(min(max_rows, len(df))):

        row = df.iloc[i]

        values = [
            str(x).strip()
            for x in row
            if pd.notna(x) and str(x).strip()
        ]

        joined = " ".join(values).lower()

        score = len(values)

        score += sum(
            keyword in joined
            for keyword in keywords
        ) * 5

        if score > best_score:
            best_score = score
            best_row = i

    if best_row is None or best_score < 2:
        raise ValueError(
            "Could not locate the CSV header row."
        )

    # Use the detected row as the new header.
    headers = []

    for value in df.iloc[best_row]:

        if pd.isna(value) or str(value).strip() == "":
            headers.append("unnamed")
        else:
            headers.append(str(value).strip())

    df = df.iloc[best_row + 1:].copy()
    df.columns = headers

    # Remove completely empty columns.
    df = df.dropna(axis=1, how="all")

    # Remove completely empty rows.
    df = df.dropna(axis=0, how="all")

    print(f"  CSV header detected at row {best_row + 1}")

    return df.reset_index(drop=True)


