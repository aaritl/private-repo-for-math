def get_world_bank_indicator(indicator_code, start_year=2010, end_year=2025):

    url = (
        f"{WORLD_BANK_BASE_URL}/country/all/indicator/"
        f"{indicator_code}"
    )

    params = {
        "format": "json",
        "per_page": 20000,
        "date": f"{start_year}:{end_year}"
    }

    response = requests.get(url, params=params, timeout=60)
    response.raise_for_status()

    result = response.json()

    if not isinstance(result, list) or len(result) < 2:
        print("No data returned for:", indicator_code)
        return pd.DataFrame()

    records = result[1]

    if records is None:
        return pd.DataFrame()

    rows = []

    for record in records:

        region = record.get("region", {}) or {}

        # Remove World Bank aggregate regions.
        if region.get("value") == "Aggregates":
            continue

        rows.append({
            "country": (record.get("country") or {}).get("value"),
            "iso3": record.get("countryiso3code"),
            "year": record.get("date"),
            "indicator_code": indicator_code,
            "value": record.get("value")
        })

    df = pd.DataFrame(rows)

    if not df.empty:
        df["value"] = pd.to_numeric(df["value"], errors="coerce")
        df["year"] = pd.to_numeric(df["year"], errors="coerce")

    return df


