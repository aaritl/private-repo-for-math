def find_value_columns(df, location_column):

    excluded = [
        "latitude", "longitude",
        "lat", "long", "id",
        "code", "rank"
    ]

    candidates = []

    for column in df.columns:

        if column == location_column:
            continue

        name = normalize_name(column)

        # Exclude geographic coordinates and identifiers.
        if any(name == x or name.startswith(x) for x in excluded):
            continue

        numeric = pd.to_numeric(
            df[column].astype(str).str.replace(",", "", regex=False),
            errors="coerce"
        )

        if numeric.notna().sum() > 0:
            candidates.append(column)

    if len(candidates) == 0:
        raise ValueError("No numeric indicator columns found.")

    return candidates


