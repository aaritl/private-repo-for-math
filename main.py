def calculate_scores(matrix, weight_table, min_coverage=MIN_DATA_COVERAGE):

    if matrix.empty or weight_table.empty:
        return pd.DataFrame()

    weights = (
        weight_table
        .set_index("indicator")["final_weight"]
        .reindex(matrix.columns)
        .fillna(0)
    )

    total_weight = weights.sum()

    if total_weight <= EPSILON:
        raise ValueError("Total indicator weight is zero.")

    available = matrix.notna()

    weighted_values = matrix.mul(weights, axis=1).fillna(0)

    available_weights = available.mul(weights, axis=1)

    numerator = weighted_values.sum(axis=1)

    denominator = available_weights.sum(axis=1)

    scores = numerator / denominator.replace(0, np.nan)

    coverage = denominator / total_weight

    results = pd.DataFrame({
        "location": matrix.index,
        "score": scores.values,
        "data_coverage": coverage.values
    })

    results["eligible"] = (
        results["data_coverage"] >= min_coverage
    )

    results["rank"] = (
        results["score"]
        .where(results["eligible"])
        .rank(method="min", ascending=False)
    )

    return results.sort_values(
        "score",
        ascending=False,
        na_position="last"
    ).reset_index(drop=True)


