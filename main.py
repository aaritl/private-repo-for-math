def normalize_name(value):
    return re.sub(r"[^a-z0-9]", "", str(value).lower())


def normalize_tier(tier):
    tier = str(tier).lower().replace(" ", "").replace("_", "")

    if "tier1" in tier:
        return "tier1"
    elif "tier2" in tier:
        return "tier2"
    elif "tier3" in tier:
        return "tier3"

    raise ValueError(f"Unknown tier: {tier}")


