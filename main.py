def process_regional_dataset(dataset_name, original_df):

    audit = {
        "dataset": dataset_name,
        "input_rows": len(original_df),
        "region_column": None,
        "country_column": None,
        "region_column_overlap": 0,
        "country_column_overlap": 0,
        "value_columns": "",
        "matched_rows": 0,
        "unmatched_rows": 0,
        "output_indicators": 0,
        "status": ""
    }

    if original_df is None or original_df.empty:
        audit["status"] = "EMPTY OR UNREADABLE DATASET"
        return pd.DataFrame(), audit, pd.DataFrame()

    df = original_df.copy()

    df.columns = [
        clean_column_name(col)
        for col in df.columns
    ]

    # Identify geography based on actual overlap with boundaries.
    region_col, country_col, region_candidates, country_candidates = (
        detect_geo_columns(df)
    )

    audit["region_column"] = region_col
    audit["country_column"] = country_col

    if region_candidates:
        audit["region_column_overlap"] = (
            sorted(region_candidates, reverse=True)[0][0]
        )

    if country_candidates:
        audit["country_column_overlap"] = (
            sorted(country_candidates, reverse=True)[0][0]
        )

    if region_col is None:
        audit["status"] = "NO ADM1 REGION NAME MATCHES"
        return pd.DataFrame(), audit, df.head(20)

    geo_columns = {region_col, country_col}

    value_columns = detect_value_columns(
        df,
        geo_columns
    )

    audit["value_columns"] = ", ".join(value_columns)

    if not value_columns:
        audit["status"] = "NO NUMERIC INDICATOR COLUMNS"
        return pd.DataFrame(), audit, df.head(20)

    year_col = detect_year_column(df)
    indicator_col = detect_indicator_column(df)

    # Match every source row to a boundary row.
    matched_indices = []
    matched_names = []
    matched_countries = []

    for _, row in df.iterrows():

        country_value = (
            row[country_col]
            if country_col is not None else None
        )

        boundary_idx = match_boundary(
            row[region_col],
            country_value
        )

        matched_indices.append(boundary_idx)

        if boundary_idx is None:
            matched_names.append(None)
            matched_countries.append(None)

        else:
            matched_names.append(
                BOUNDARIES.loc[
                    boundary_idx,
                    BOUNDARY_REGION_COL
                ]
            )

            matched_countries.append(
                BOUNDARIES.loc[
                    boundary_idx,
                    BOUNDARY_COUNTRY_COL
                ]
            )

    df["_boundary_idx"] = matched_indices
    df["_matched_region"] = matched_names
    df["_matched_country"] = matched_countries

    matched = df[df["_boundary_idx"].notna()].copy()

    unmatched = df[df["_boundary_idx"].isna()].copy()

    audit["matched_rows"] = len(matched)
    audit["unmatched_rows"] = len(unmatched)

    if matched.empty:
        audit["status"] = "NO GEOGRAPHIC MATCHES"
        return pd.DataFrame(), audit, unmatched.head(20)

    output_frames = []

    for value_col in value_columns:

        temp = matched.copy()

        # Convert numeric values; remove commas from formatted numbers.
        temp["value"] = pd.to_numeric(
            temp[value_col].astype(str).str.replace(
                ",", "", regex=False
            ),
            errors="coerce"
        )

        temp = temp.dropna(subset=["value"])

        temp = temp[
            np.isfinite(temp["value"])
        ].copy()

        if temp.empty:
            continue

        if indicator_col is not None:

            labels = (
                temp[indicator_col]
                .fillna(value_col)
                .astype(str)
                .str.strip()
            )

            # Retain source-column identity when multiple value
            # columns exist.
            if len(value_columns) > 1:
                labels = dataset_name + "_" + value_col + "_" + labels

            else:
                labels = dataset_name + "_" + labels

        else:
            labels = dataset_name + "_" + value_col

        temp["indicator"] = labels

        temp["location"] = temp["_matched_region"]
        temp["country"] = temp["_matched_country"]
        temp["source"] = dataset_name
        temp["tier"] = "Tier 2"

        if year_col is not None:
            temp["year"] = temp[year_col]
        else:
            temp["year"] = np.nan

        output_frames.append(
            temp[
                [
                    "tier",
                    "country",
                    "location",
                    "indicator",
                    "value",
                    "year",
                    "source"
                ]
            ]
        )

    if not output_frames:
        audit["status"] = "MATCHED REGIONS BUT NO VALID VALUES"
        return pd.DataFrame(), audit, unmatched.head(20)

    result = pd.concat(
        output_frames,
        ignore_index=True
    )

    audit["output_indicators"] = result["indicator"].nunique()
    audit["status"] = "SUCCESS"

    return result, audit, unmatched.head(20)


