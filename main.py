def parse_homicide_csv(filename):

    """
    Tries multiple delimiters and quote-handling methods.
    Returns a DataFrame only when a credible multi-column
    parse is found.

    Malformed rows are skipped only during fallback parsing.
    """

    if not os.path.exists(filename):
        raise FileNotFoundError(filename)

    candidates = []

    delimiters = [",", ";", "\t", "|"]

    # Attempt normal CSV parsing with multiple quote settings.
    for delimiter in delimiters:

        for quotechar in ['"', "'", None]:

            try:

                options = {
                    "filepath_or_buffer": filename,
                    "sep": delimiter,
                    "encoding": "utf-8-sig",
                    "engine": "python",
                    "on_bad_lines": "skip",
                    "skipinitialspace": True
                }

                if quotechar is None:
                    options["quoting"] = csv.QUOTE_NONE
                    options["escapechar"] = "\\"
                else:
                    options["quotechar"] = quotechar

                parsed = pd.read_csv(**options)

                parsed = parsed.dropna(axis=1, how="all")
                parsed = parsed.dropna(axis=0, how="all")

                if parsed.shape[1] >= 2 and len(parsed) > 0:

                    # Reject implausible parses with excessive columns.
                    if parsed.shape[1] > 100:
                        continue

                    score = (
                        len(parsed) *
                        min(parsed.shape[1], 20)
                    )

                    candidates.append(
                        (score, parsed, delimiter, quotechar)
                    )

            except Exception:
                pass

    # Fallback: manually unwrap rows that may have been
    # imported as a single quoted column.
    if not candidates:

        with open(
            filename,
            "r",
            encoding="utf-8-sig",
            errors="replace"
        ) as file:

            lines = [
                line.strip()
                for line in file
                if line.strip()
            ]

        for delimiter in delimiters:

            parsed_rows = []

            for line in lines:

                # Remove one enclosing quote pair if present.
                stripped = line.strip()

                if (
                    len(stripped) >= 2 and
                    stripped[0] == stripped[-1] and
                    stripped[0] in ['"', "'"]
                ):
                    stripped = stripped[1:-1]

                try:
                    row = next(
                        csv.reader(
                            [stripped],
                            delimiter=delimiter,
                            quotechar='"'
                        )
                    )
                except Exception:
                    row = stripped.split(delimiter)

                parsed_rows.append(row)

            if not parsed_rows:
                continue

            widths = pd.Series(
                [len(row) for row in parsed_rows]
            ).value_counts()

            expected_width = int(widths.index[0])

            # Require at least two columns and a consistent structure.
            if expected_width < 2:
                continue

            consistent_rows = [
                row for row in parsed_rows
                if len(row) == expected_width
            ]

            if len(consistent_rows) < 2:
                continue

            parsed = pd.DataFrame(
                consistent_rows[1:],
                columns=[
                    str(x).strip()
                    for x in consistent_rows[0]
                ]
            )

            if parsed.shape[1] >= 2:

                score = len(parsed) * min(parsed.shape[1], 20)

                candidates.append(
                    (score, parsed, delimiter, "manual")
                )

    if not candidates:
        raise ValueError(
            "No credible multi-column CSV structure was found. "
            "The file may genuinely contain only one column or "
            "may use a different export format."
        )

    candidates.sort(
        key=lambda item: item[0],
        reverse=True
    )

    _, best, delimiter, quotechar = candidates[0]

    # Validate that the first row is not entirely empty.
    best = best.dropna(axis=1, how="all")
    best = best.dropna(axis=0, how="all")

    if best.shape[1] < 2:
        raise ValueError("Parsed file still contains only one column.")

    return best, delimiter, quotechar


