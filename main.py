def find_location_column(df):

    keywords = [
        "country", "countryname",
        "location", "city", "cityname",
        "region", "regionname",
        "geoarea", "geographicarea",
        "urbanarea", "municipality",
        "province", "state", "place"
    ]

    matches = []

    for column in df.columns:

        name = normalize_name(column)

        if any(keyword in name for keyword in keywords):
            matches.append(column)

    preferred = [
        "country", "countryname",
        "location", "city", "cityname",
        "region", "regionname", "geoarea"
    ]

    for preferred_name in preferred:

        for column in matches:

            if normalize_name(column) == preferred_name:
                return column

    if len(matches) == 1:
        return matches[0]

    if len(matches) == 0:

        raise ValueError(
            "No geographic column identified. "
            f"Available columns: {list(df.columns)}"
        )

    raise ValueError(
        f"Multiple geographic columns found: {matches}. "
        "Set location_column in Cell 6."
    )


