    # Perturb weights around their baseline values.
    alpha = np.maximum(
        active_weights.values * DIRICHLET_CONCENTRATION,
        0.02
    )

    sampled_weights = rng.dirichlet(alpha)

    sampled_weights = pd.Series(
        sampled_weights,
        index=active_weights.index
    )

    # Score each country with available observations only.
    for index, row in simulation_data.iterrows():

        available = row.notna()

        available_weights = sampled_weights[
            available.reindex(sampled_weights.index).fillna(False).values
        ]

        if available_weights.sum() <= 0:
            score = np.nan

        else:

            valid_criteria = available_weights.index

            score = sum(
                row[col] * available_weights[col]
                for col in valid_criteria
            ) / available_weights.sum()

        draw_results.append({
            "country": tier2_data.loc[index, "country"],
            "draw": draw,
            "score": score
        })

