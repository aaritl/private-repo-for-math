def match_boundary(region_value, country_value=None):

    region_key = normalize_place(region_value)

    if not region_key:
        return None

    country_key = normalize_country(country_value)

    # First preference: exact country + region
    if country_key:

        combined_key = country_key + "|" + region_key

        candidates = COMBINED_LOOKUP.get(combined_key, [])

        if len(candidates) == 1:
            return candidates[0]

        # Ambiguous country-region key is not accepted.
        if len(candidates) > 1:
            return None

    # Second preference: region-only match, but only if unique.
    return UNIQUE_REGION_LOOKUP.get(region_key)


