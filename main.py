def entropy_weights(matrix):

    """
    Calculate entropy weights for columns in a normalized matrix.

    Missing values are excluded from each indicator's entropy
    calculation. Missing observations are not automatically
    replaced with zero.
    """

    if matrix.empty or matrix.shape[1] == 0:
        return pd.Series(dtype=float)

    information = {}

    for column in matrix.columns:

        values = matrix[column].dropna().astype(float)

        n = len(values)

        if n <= 1:
            information[column] = 0.0
            continue

        values = values.clip(lower=0) + EPSILON

        proportions = values / values.sum()

        entropy = -(
            proportions * np.log(proportions)
        ).sum() / np.log(n)

        divergence = max(0.0, 1 - entropy)

        information[column] = divergence

    information = pd.Series(information, dtype=float)

    if information.sum() <= EPSILON:
        # Equal fallback when all indicators have zero
        # discriminatory information.
        return pd.Series(
            1 / len(information),
            index=information.index
        )

    return information / information.sum()


def hierarchical_entropy_weights(matrix, tier):

    """
    Step 1: Calculate each category's average normalized score.
    Step 2: Calculate entropy weights across categories.
    Step 3: Calculate entropy weights among indicators within
            each category.
    Step 4: Multiply category and within-category weights.
    """

    if matrix.empty:
        return pd.DataFrame(), pd.Series(dtype=float)

    active_criteria = {
        name: config
        for name, config in CRITERIA.items()
        if config["tier"] == tier and name in matrix.columns
    }

    if not active_criteria:
        return pd.DataFrame(), pd.Series(dtype=float)

    indicator_to_category = {
        name: config["category"]
        for name, config in active_criteria.items()
    }

    categories = sorted(set(indicator_to_category.values()))

    # Build one average score for each category and location.
    category_matrix = pd.DataFrame(index=matrix.index)

    for category in categories:

        indicators = [
            indicator
            for indicator, assigned_category in indicator_to_category.items()
            if assigned_category == category
        ]

        category_matrix[category] = matrix[indicators].mean(axis=1)

    category_weights = entropy_weights(category_matrix)

    results = []

    for category in categories:

        indicators = [
            indicator
            for indicator, assigned_category in indicator_to_category.items()
            if assigned_category == category
        ]

        within_category_weights = entropy_weights(
            matrix[indicators]
        )

        category_weight = category_weights.get(category, 0)

        for indicator in indicators:

            within_weight = within_category_weights.get(
                indicator,
                0
            )

            final_weight = category_weight * within_weight

            results.append({
                "tier": tier,
                "category": category,
                "indicator": indicator,
                "category_weight": category_weight,
                "within_category_weight": within_weight,
                "final_weight": final_weight
            })

    weight_table = pd.DataFrame(results)

    return weight_table, category_weights


