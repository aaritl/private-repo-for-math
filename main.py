def minmax_normalize(series, direction):

    values = pd.to_numeric(series, errors="coerce")

    minimum = values.min()
    maximum = values.max()

    # Handle entirely missing indicators
    if pd.isna(minimum) or pd.isna(maximum):
        return pd.Series(np.nan, index=series.index)

    # Handle indicators with no variation
    if maximum == minimum:
        return pd.Series(0.5, index=series.index)

    # Standard Min-Max normalization
    normalized = (values - minimum) / (maximum - minimum)

    # Reverse cost indicators so higher scores are better
    if direction == "cost":
        normalized = 1 - normalized

    elif direction != "benefit":
        raise ValueError(
            "Direction must be 'benefit' or 'cost'."
        )

    return normalized.clip(0, 1)


