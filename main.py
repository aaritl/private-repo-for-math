def detect_value_columns(df, geo_columns):

    value_columns = []

    for col in df.columns:

        if col in geo_columns or col is None:
            continue

        name = col.lower()

        if any(term in name for term in NON_INDICATOR_TERMS):
            continue

        numeric = pd.to_numeric(
            df[col].astype(str).str.replace(",", "", regex=False),
            errors="coerce"
        )

        valid_count = numeric.notna().sum()

        if valid_count == 0:
            continue

        # Exclude columns that are almost entirely identifiers.
        valid_fraction = valid_count / max(len(df), 1)

        if valid_fraction < 0.05:
            continue

        value_columns.append(col)

    # If there are explicit value fields, prefer those.
    preferred = [
        col for col in value_columns
        if any(term in col.lower() for term in VALUE_TERMS)
    ]

    if preferred:
        return preferred

    return value_columns


