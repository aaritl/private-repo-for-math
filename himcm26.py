# CELL 14 — RUN THE SENSITIVITY TEST
# Weights stay fixed at the baseline entropy weights. Otherwise changing one
# value would also shift the weights, and the effect of the value change
# couldn't be told apart from the effect of the weight change.
# CHANGED: this cell appeared twice, word for word; the second copy was removed.

TIER_RESULTS = {
    "tier1_country": {
        "data": country_data, "loaded": tier1_loaded, "weights": tier1_weights
    },
    "tier2_region": {
        "data": region_data, "loaded": tier2_loaded, "weights": tier2_weights
    },
    "tier3_city": {
        "data": city_data, "loaded": tier3_loaded, "weights": tier3_weights
    }
}

if SENSITIVITY_TIER not in TIER_RESULTS:
    raise ValueError("SENSITIVITY_TIER must be tier1_country, tier2_region, or tier3_city.")

sens = TIER_RESULTS[SENSITIVITY_TIER]
if SENSITIVITY_CRITERION not in sens["loaded"]:
    raise ValueError(
        f"{SENSITIVITY_CRITERION} is not loaded. "
        f"Available: {sens['loaded']}"
    )

# CHANGED: the baseline uses the stored weights (sens["weights"]), the same
# fixed-weight path as the test runs, so the overridden value is the only
# difference between them. The original recalculated the weights from scratch,
# which was redundant.
base_scored, _, _ = score_tier(
    sens["data"], SENSITIVITY_TIER, sens["loaded"], fixed_weights=sens["weights"]
)
target_mask = base_scored["geo_id"].astype(str) == str(SENSITIVITY_GEO_ID)
target_base = base_scored[target_mask]
if target_base.empty:
    raise ValueError("Target ID not found in this tier's scored dataset.")
target_base = target_base.iloc[0]

# CHANGED: baseline_value used to be computed and then ignored. It is now a
# reference row and a red marker on both plots. A missing value gets a clear
# note instead of silently becoming NaN.
baseline_value = target_base[SENSITIVITY_CRITERION]
if pd.isna(baseline_value):
    print(f"Note: {SENSITIVITY_GEO_ID} has no observed {SENSITIVITY_CRITERION}; "
          "the tests below add a value where there was none.")
if pd.isna(target_base["rank"]):
    print(f"Note: {SENSITIVITY_GEO_ID} is below MIN_DATA_COVERAGE at baseline, so it has no rank.")

sensitivity_rows = [{
    "tier": SENSITIVITY_TIER,
    "geo_id": SENSITIVITY_GEO_ID,
    "criterion": SENSITIVITY_CRITERION,
    "scenario": "baseline",
    "tested_value": baseline_value,
    "mcda_score": target_base["mcda_score"],
    "rank": target_base["rank"],
    "data_coverage": target_base["data_coverage"]
}]
# Rerun the scoring once per test value. Every place is re-normalized each
# time, so the rank reflects the full effect of the change.
for test_value in TEST_VALUES:
    scenario_scored, _, _ = score_tier(
        sens["data"],
        SENSITIVITY_TIER,
        sens["loaded"],
        fixed_weights=sens["weights"],
        override=(SENSITIVITY_CRITERION, SENSITIVITY_GEO_ID, test_value)
    )
    target_row = scenario_scored[
        scenario_scored["geo_id"].astype(str) == str(SENSITIVITY_GEO_ID)
    ].iloc[0]

    sensitivity_rows.append({
        "tier": SENSITIVITY_TIER,
        "geo_id": SENSITIVITY_GEO_ID,
        "criterion": SENSITIVITY_CRITERION,
        "scenario": "test",
        "tested_value": test_value,
        "mcda_score": target_row["mcda_score"],
        "rank": target_row["rank"],
        "data_coverage": target_row["data_coverage"]
    })

sensitivity_results = pd.DataFrame(sensitivity_rows)
display(sensitivity_results)

