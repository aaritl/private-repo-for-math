SENSITIVITY_TIER = "tier3_city"             # tier1_country / tier2_region / tier3_city
SENSITIVITY_CRITERION = "restaurants_per_10000"
SENSITIVITY_GEO_ID = "YOUR_CITY_GEONAME_ID" # replace with an ID in the scored tier

# Replace these example values with plausible values in the criterion's real unit.
TEST_VALUES = [20, 30, 40, 50, 60]

