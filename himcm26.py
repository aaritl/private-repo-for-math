def load_tier_indicators(tier_name, registry):
    """
    Attach each populated criterion CSV to the registry as one column.
    Returns (data, loaded): data has one row per place and one column per
    loaded criterion (NaN where a place has no value); loaded lists those criteria.
    """
    data = registry.copy()
    data["geo_id"] = data["geo_id"].astype(str)
    registry_ids = set(data["geo_id"])
    metadata = flatten_criteria(tier_name)
    folder = TIER_FOLDERS[tier_name]
    indicator_columns = {}            # criterion_key -> Series indexed by geo_id

    for criterion_key in metadata:
        path = folder / f"{criterion_key}.csv"
        if not path.exists():
            continue

        # CHANGED: read geo_id as text with NA_SAFE. Before, "NA" (Namibia)
        # became NaN, and numeric city IDs in a column with any blank became
        # "123.0", which never matches "123". Either way the data was lost
        # without an error.
        indicator = pd.read_csv(path, dtype={"geo_id": str}, **NA_SAFE)
        required = {"geo_id", "value"}
        missing_columns = required - set(indicator.columns)
        if missing_columns:
            raise ValueError(f"{path.name} is missing columns: {missing_columns}")

        # CHANGED: strip stray spaces left by hand-edited spreadsheets (" US").
        indicator["geo_id"] = indicator["geo_id"].str.strip()
        # errors="coerce": text such as "n/a" becomes NaN instead of crashing.
        indicator[criterion_key] = pd.to_numeric(indicator["value"], errors="coerce")

        # CHANGED: drop rows with no usable value *before* removing duplicates,
        # so a blank first row can no longer win over a later row with data.
        indicator = indicator.dropna(subset=["geo_id", criterion_key])

        # A template that was never filled in is skipped, so only criteria
        # with real data take part in scoring.
        if indicator.empty:
            continue

        # CHANGED: if a place has several rows (several years), keep the newest
        # year instead of whichever row happens to come first.
        if "year" in indicator.columns:
            indicator["_year"] = pd.to_numeric(indicator["year"], errors="coerce")
            indicator = indicator.sort_values("_year", ascending=False, na_position="last")
        indicator = indicator.drop_duplicates("geo_id")

        # CHANGED: report IDs that match no place, so a typo in geo_id no
        # longer disappears silently. (In tiers 2-3 this also lists places
        # screened out earlier, which is expected.)
        unmatched = sorted(set(indicator["geo_id"]) - registry_ids)
        if unmatched:
            print(
                f"Note: {path.name}: {len(unmatched)} geo_id(s) not in this tier's "
                f"candidate set (typo, or screened out earlier). e.g. {unmatched[:5]}"
            )

        indicator_columns[criterion_key] = indicator.set_index("geo_id")[criterion_key]

    if not indicator_columns:
        raise ValueError(
            f"No populated criterion CSVs found for {tier_name}. "
            f"Fill at least one template in {folder} and rerun."
        )

    # CHANGED (optimization): one join for all criteria, instead of one merge
    # per criterion. Each merge copied the whole table, so this does less
    # work. A left join keeps every registry place, including those without data.
    data = data.join(pd.DataFrame(indicator_columns), on="geo_id")
    return data, list(indicator_columns)

def normalize_series(series, direction):
    """
    Min-max normalization: x' = (x - min) / (max - min), giving values in [0, 1].
    Cost criteria use 1 - x', so 1 is always the best place and 0 the worst.
    This puts criteria in different units (%, $, per 1,000) on one scale.
    Missing values stay missing; they are never treated as 0.
    """
    x = pd.to_numeric(series, errors="coerce")
    minimum, maximum = x.min(), x.max()     # pandas skips NaN when finding these

    if pd.isna(minimum) or pd.isna(maximum):
        return pd.Series(np.nan, index=x.index)

    if np.isclose(maximum, minimum):
        # Every place has the same value, so this criterion can't separate
        # them, and max - min = 0 would divide by zero. Give everyone 0.5.
        return pd.Series(0.5, index=x.index).where(x.notna())

    normalized = (x - minimum) / (maximum - minimum)
    if direction == "cost":
        normalized = 1 - normalized
    return normalized.clip(0, 1)            # guards against floating-point overshoot

def calculate_entropy_weights(normalized_df):
    """
    Entropy weight method (objective weighting). For criterion j over n places:
        p_ij = x_ij / sum_i x_ij               each place's share of the column
        e_j  = -(1 / ln n) * sum_i p_ij ln p_ij   entropy, between 0 and 1
        d_j  = 1 - e_j                         how much the criterion varies
        w_j  = d_j / sum_j d_j                 weights add up to 1
    If every place has the same value, e_j = 1, d_j = 0, and the weight is 0
    (no information). Criteria that spread places out unevenly get more weight.
    """
    X = normalized_df.copy().astype(float)

    # CHANGED: use only places with at least one observed value. Before, every
    # registry row went in (about 250 countries even when only 40 had data).
    # Places with no data were filled with column means, which pushed every
    # e_j toward 1, so the weights depended on registry size, not on the data.
    X = X.dropna(how="all")

    # A criterion needs at least 2 observations and 2 distinct values to carry information.
    usable = []
    for col in X.columns:
        observed = X[col].dropna()
        if len(observed) >= 2 and observed.nunique() > 1:
            usable.append(col)

    if not usable:
        if len(normalized_df.columns) == 0:
            return pd.Series(dtype=float)
        # No criterion separates the places, so equal weights is the neutral choice.
        return pd.Series(1 / len(normalized_df.columns), index=normalized_df.columns)

    X = X[usable].copy()
    # Fill gaps with the column mean (used for estimating weights only; scores
    # never use these filled values). This slightly lowers a criterion's spread
    # in proportion to its missing data, a fair penalty for patchy data.
    X = X.apply(lambda col: col.fillna(col.mean()), axis=0)
    # CHANGED: removed X.clip(lower=0), which never changed anything because
    # values are already in [0, 1].

    # min-max makes each column's worst place exactly 0, and ln(0) is undefined;
    # a tiny shift avoids it without changing the result in any meaningful way.
    P = X + 1e-12
    P = P.div(P.sum(axis=0), axis=1)        # p_ij: each column now sums to 1

    n = len(P)
    if n <= 1:
        # ln(1) = 0 would divide by zero, and one place can't be compared with anything.
        return pd.Series(1 / len(usable), index=usable).reindex(
            normalized_df.columns, fill_value=0.0
        )  # CHANGED: return every criterion (0 for unusable) so the result's shape is always the same.

    k = 1 / np.log(n)                       # scales e_j into [0, 1]
    entropy = -k * (P * np.log(P)).sum(axis=0)
    divergence = (1 - entropy).clip(lower=0)

    if divergence.sum() <= 1e-12:
        weights = pd.Series(1 / len(usable), index=usable)
    else:
        weights = divergence / divergence.sum()

    # Put the unusable criteria back with weight 0, so every criterion appears in the output.
    final = pd.Series(0.0, index=normalized_df.columns)
    final.loc[weights.index] = weights
    return final

# CELL 8 — SCORE A TIER USING ENTROPY WEIGHTS

def score_tier(data, tier_name, loaded_criteria, fixed_weights=None,
               override=None, min_coverage=None):
    """
    Score every place in one tier.
        score_i    = sum_j(w_j * x'_ij) / sum_j(w_j), summing only over criteria place i has
        coverage_i = sum_j(w_j over criteria place i has) / sum_j(w_j)
    A missing value is skipped, not counted as 0, so missing data neither helps
    nor hurts the score. Coverage records how much evidence stands behind it.

    override: optional tuple (criterion_key, geo_id, replacement_raw_value).
    fixed_weights: optional Series of weights to hold constant (used in the sensitivity test).
    min_coverage: places below this coverage get a score but no rank.
        None = use MIN_DATA_COVERAGE, read when the function runs, so a changed
        setting takes effect without rerunning this cell.
    Returns (scored data sorted best-first, weights, normalized matrix).
    """
    if min_coverage is None:
        min_coverage = MIN_DATA_COVERAGE
    metadata = flatten_criteria(tier_name)
    work = data.copy()                      # never modify the caller's data

    if override is not None:
        criterion_key, target_geo_id, replacement_value = override
        if criterion_key not in loaded_criteria:
            raise ValueError(f"{criterion_key} is not loaded in {tier_name}.")
        mask = work["geo_id"].astype(str) == str(target_geo_id)
        if not mask.any():
            raise ValueError(f"geo_id {target_geo_id} was not found in this tier.")
        work.loc[mask, criterion_key] = float(replacement_value)

    # Normalization runs after the override on purpose: a test value outside the
    # old min/max stretches the scale for everyone, just as real new data would.
    normalized = pd.DataFrame(index=work.index)
    for key in loaded_criteria:
        normalized[key] = normalize_series(
            work[key], metadata[key]["direction"]
        )

    if fixed_weights is None:
        weights = calculate_entropy_weights(normalized)
    else:
        weights = fixed_weights.reindex(loaded_criteria).fillna(0.0)
        if weights.sum() <= 0:
            weights = pd.Series(1 / len(loaded_criteria), index=loaded_criteria)
        else:
            weights = weights / weights.sum()    # rescale so the weights add up to 1

    # Each value times its weight. NaN * w stays NaN, so missing data is skipped.
    weighted_values = normalized.mul(weights, axis=1)
    # Total weight of the criteria each place actually has data for.
    available_weight = normalized.notna().mul(weights, axis=1).sum(axis=1)
    # min_count=1: a place with no data gets NaN, not a fake score of 0.
    weighted_sum = weighted_values.sum(axis=1, min_count=1)

    # Divide by the available weight (not by 1) to rescale over the criteria the place has.
    work["mcda_score"] = weighted_sum / available_weight.replace(0, np.nan)
    work["data_coverage"] = available_weight / weights.sum()

    # CHANGED: rank only places that meet the coverage threshold. Before,
    # low-coverage places took up rank numbers and were then removed, which
    # left gaps (1, 2, 5, ...). method="min": tied places share the best rank.
    eligible = work["mcda_score"].notna() & (work["data_coverage"] >= min_coverage)
    work["rank"] = work["mcda_score"].where(eligible).rank(method="min", ascending=False)

    return work.sort_values("mcda_score", ascending=False), weights, normalized

def keep_top_n(data, n, minimum_score=None, group_column=None):
    """
    Keep the top N places overall (group_column=None), or the top N inside each
    parent (e.g. 5 regions per country). The per-parent version keeps the
    shortlist spread out, so one strong country can't take every slot.
    """
    result = data.dropna(subset=["mcda_score"]).copy()
    if minimum_score is not None:
        result = result[result["mcda_score"] >= minimum_score]
    if group_column is None:
        return result.nlargest(n, "mcda_score")
    # Sort once, best first; head(n) then takes each group's first n rows.
    return (
        result.sort_values("mcda_score", ascending=False)
        .groupby(group_column, group_keys=False)
        .head(n)
    )

