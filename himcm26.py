def flatten_criteria(tier_name):
    "Return {criterion_key: metadata} for one tier."
    return {
        key: details
        for category in CRITERIA[tier_name].values()
        for key, details in category.items()
    }

def load_tier_indicators(tier_name, registry):
    "Merge the available per-criterion CSVs onto a geographic registry."
    data = registry.copy()
    data["geo_id"] = data["geo_id"].astype(str)
    metadata = flatten_criteria(tier_name)
    folder = TIER_FOLDERS[tier_name]
    loaded = []

    for criterion_key in metadata:
        path = folder / f"{criterion_key}.csv"
        if not path.exists():
            continue

        indicator = pd.read_csv(path)
        required = {"geo_id", "value"}
        missing_columns = required - set(indicator.columns)
        if missing_columns:
            raise ValueError(f"{path.name} is missing columns: {missing_columns}")

        indicator["geo_id"] = indicator["geo_id"].astype(str)
        indicator[criterion_key] = pd.to_numeric(indicator["value"], errors="coerce")
        indicator = indicator[["geo_id", criterion_key]].drop_duplicates("geo_id")
        # Ignore untouched blank templates; only populated files become active criteria.
        if not indicator[criterion_key].notna().any():
            continue
        data = data.merge(indicator, on="geo_id", how="left")
        loaded.append(criterion_key)

    if not loaded:
        raise ValueError(
            f"No populated criterion CSVs found for {tier_name}. "
            f"Fill at least one template in {folder} and rerun."
        )

    return data, loaded

def normalize_series(series, direction):
    "Min-Max normalize one criterion; leave missing values missing."
    x = pd.to_numeric(series, errors="coerce")
    minimum, maximum = x.min(), x.max()

    if pd.isna(minimum) or pd.isna(maximum):
        return pd.Series(np.nan, index=x.index)

    if np.isclose(maximum, minimum):
        # A constant criterion does not distinguish places.
        return pd.Series(0.5, index=x.index).where(x.notna())

    normalized = (x - minimum) / (maximum - minimum)
    if direction == "cost":
        normalized = 1 - normalized
    return normalized.clip(0, 1)

def calculate_entropy_weights(normalized_df):
    "Entropy weights; missing normalized values are mean-imputed for weight estimation only."
    X = normalized_df.copy().astype(float)

    # Remove criteria with no observations or no variation.
    usable = []
    for col in X.columns:
        observed = X[col].dropna()
        if len(observed) >= 2 and observed.nunique() > 1:
            usable.append(col)

    if not usable:
        if len(X.columns) == 0:
            return pd.Series(dtype=float)
        return pd.Series(1 / len(X.columns), index=X.columns)

    X = X[usable].copy()
    X = X.apply(lambda col: col.fillna(col.mean()), axis=0)
    X = X.clip(lower=0)

    # Shift tiny values to avoid zero column totals.
    P = X + 1e-12
    P = P.div(P.sum(axis=0), axis=1)

    n = len(P)
    if n <= 1:
        return pd.Series(1 / len(usable), index=usable)

    k = 1 / np.log(n)
    entropy = -k * (P * np.log(P)).sum(axis=0)
    divergence = (1 - entropy).clip(lower=0)

    if divergence.sum() <= 1e-12:
        weights = pd.Series(1 / len(usable), index=usable)
    else:
        weights = divergence / divergence.sum()

    # Criteria that had no variation receive zero weight.
    final = pd.Series(0.0, index=normalized_df.columns)
    final.loc[weights.index] = weights
    return final

# CELL 8 — SCORE A TIER USING ENTROPY WEIGHTS

def score_tier(data, tier_name, loaded_criteria, fixed_weights=None, override=None):
    """
    Score all entities in a tier.
    override: optional tuple (criterion_key, geo_id, replacement_raw_value).
    fixed_weights: optional Series to hold weights constant during sensitivity tests.
    """
    metadata = flatten_criteria(tier_name)
    work = data.copy()

    if override is not None:
        criterion_key, target_geo_id, replacement_value = override
        if criterion_key not in loaded_criteria:
            raise ValueError(f"{criterion_key} is not loaded in {tier_name}.")
        mask = work["geo_id"].astype(str) == str(target_geo_id)
        if not mask.any():
            raise ValueError(f"geo_id {target_geo_id} was not found in this tier.")
        work.loc[mask, criterion_key] = float(replacement_value)

    normalized = pd.DataFrame(index=work.index)
    for key in loaded_criteria:
        normalized[key] = normalize_series(
            work[key], metadata[key]["direction"]
        )

    if fixed_weights is None:
        weights = calculate_entropy_weights(normalized)
    else:
        weights = fixed_weights.reindex(loaded_criteria).fillna(0.0)
        if weights.sum() <= 0:
            weights = pd.Series(1 / len(loaded_criteria), index=loaded_criteria)
        else:
            weights = weights / weights.sum()

    # A missing indicator is omitted for that entity; available weights are re-scaled.
    weighted_values = normalized.mul(weights, axis=1)
    available_weight = normalized.notna().mul(weights, axis=1).sum(axis=1)
    weighted_sum = weighted_values.sum(axis=1, min_count=1)

    work["mcda_score"] = weighted_sum / available_weight.replace(0, np.nan)
    work["data_coverage"] = available_weight / weights.sum()
    work["rank"] = work["mcda_score"].rank(method="min", ascending=False)

    return work.sort_values("mcda_score", ascending=False), weights, normalized

def keep_top_n(data, n, minimum_score=None, group_column=None):
    "Keep top N overall, or top N within each parent group."
    result = data.dropna(subset=["mcda_score"]).copy()
    if minimum_score is not None:
        result = result[result["mcda_score"] >= minimum_score]
    if group_column is None:
        return result.nlargest(n, "mcda_score")
    return (
        result.sort_values("mcda_score", ascending=False)
        .groupby(group_column, group_keys=False)
        .head(n)
    )

